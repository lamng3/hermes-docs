#!/usr/bin/env python3
"""Export Hermes's leaderboard for the manual's arena page.

    python3 leaderboard_data.py [../hermes/results/LEADERBOARD.md]

LEADERBOARD.md is generated by `hermes report --write` from every run's metrics.json and from the official peer scores.
This reads its score and cost tables per benchmark; the page ranks and sorts them and computes nothing else.
"""

import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent
SOURCE = Path(sys.argv[1] if len(sys.argv) > 1 else ROOT.parent / "hermes/results/LEADERBOARD.md")
BOARDS = {
    "ck26": ("Corporate (ck26)", "Text2SPARQL 2026, the corporate knowledge graph: 100 questions, English and German, scored by the official scorer."),
    "db26": ("DBpedia (db26)", "Text2SPARQL 2026, the DBpedia track. Hermes ran only the training-free baseline here."),
}


def tables(section):
    """Markdown tables in a section: a list of (header cells, rows of cells)."""
    out, block = [], []
    for line in section.splitlines() + [""]:
        if line.startswith("|"):
            block.append([c.strip() for c in line.strip().strip("|").split("|")])
        elif block:
            header, _, *rows = block
            out.append((header, rows))
            block = []
    return out


def number(text):
    m = re.search(r"-?\d[\d,]*\.?\d*", text or "")
    return float(m.group(0).replace(",", "")) if m else None


def main():
    text = SOURCE.read_text()
    sections = {m.group(1): m.group(2) for m in re.finditer(r"^## (\w+)\n(.*?)(?=^## |\Z)", text, re.S | re.M)}
    boards = []
    for key, (name, sub) in BOARDS.items():
        score_table, cost_table = (tables(sections[key]) + [None, None])[:2]
        cost = {}
        if cost_table:
            header, rows = cost_table
            for row in rows:
                d = dict(zip(header, row))
                cost[d["system"]] = {"calls": number(d.get("LLM calls/item")), "gpu": number(d.get("cost (USD)"))}
        header, rows = score_table
        out = []
        for row in rows:
            d = dict(zip(header, row))
            official = d["system"].endswith("(official)")
            run = d["system"].replace(" (official)", "")
            values = {"f1": number(d["F1"]), "p": number(d["P"]), "r": number(d["R"]), "strict": number(d.get("strict F1"))}
            tag = d.get("model", "").replace("Qwen/", "")
            if run.endswith("-gold-oracle"):
                tag = "oracle: sees the gold query"
            if not official:
                values["calls"] = (cost.get(run) or {}).get("calls")
                values["gpu"] = (cost.get(run) or {}).get("gpu")
            out.append({"name": run, "group": "official" if official else "hermes", "tag": tag, "score": number(d["set_F_ndcg"]), "values": values})
        boards.append(
            {
                "id": key, "name": name, "sub": sub, "metric": "set_F_ndcg", "metricLabel": "Set F-nDCG", "fmt": "f3",
                "columns": [
                    {"key": "f1", "label": "F1", "fmt": "f3"}, {"key": "p", "label": "Precision", "fmt": "f3"},
                    {"key": "r", "label": "Recall", "fmt": "f3"}, {"key": "calls", "label": "LLM calls / item", "fmt": "f1"},
                    {"key": "gpu", "label": "GPU min", "fmt": "f1"},
                ],
                "rows": out,
            }
        )
    data = {
        "note": f"Scores are the official Text2SPARQL 2026 scorer's set F-nDCG; Hermes rows are runs of this repository, official rows are the challenge's published peer scores. Generated from {SOURCE.name} by hermes report; GPU minutes are for local models.",
        "groups": {"hermes": {"label": "Hermes", "ours": True}, "official": {"label": "Official"}},
        "boards": boards,
    }
    (ROOT / "leaderboard-data.json").write_text(json.dumps(data))
    print(", ".join(f"{b['id']}: {len(b['rows'])} rows" for b in boards))


if __name__ == "__main__":
    main()
